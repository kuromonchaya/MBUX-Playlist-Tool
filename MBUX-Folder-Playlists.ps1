param(
    [ValidateSet('Direct','Recursive')]
    [string]$Mode = 'Direct'
)

$ErrorActionPreference = 'Stop'

# The USB root is the folder containing this script.
$Root = Split-Path -Parent $MyInvocation.MyCommand.Path
$Root = (Resolve-Path -LiteralPath $Root).Path.TrimEnd('\')

# Common audio formats. Add/remove extensions here if needed.
$AudioExtensions = @(
    '.mp3', '.m4a', '.aac', '.flac', '.wav', '.wma', '.ogg', '.opus'
)

# Generated playlist files are placed in the USB root.
# The prefix makes them easy to identify and safely regenerate.
$PlaylistPrefix = 'MBUX - '
$PlaylistExtension = '.m3u'
$CreateAllUsbPlaylist = $true

# Skip Windows/system folders that may appear on removable drives.
$ExcludedDirectoryNames = @(
    '$RECYCLE.BIN',
    'System Volume Information'
)

function Test-IsAudioFile {
    param([System.IO.FileInfo]$File)
    return $AudioExtensions -contains $File.Extension.ToLowerInvariant()
}

function Get-UsbRelativePath {
    param([string]$FullPath)

    if (-not $FullPath.StartsWith($Root, [System.StringComparison]::OrdinalIgnoreCase)) {
        throw "Path is outside USB root: $FullPath"
    }

    return $FullPath.Substring($Root.Length).TrimStart('\')
}

function Test-IsExcludedPath {
    param([string]$FullPath)

    $relative = Get-UsbRelativePath $FullPath
    if ([string]::IsNullOrWhiteSpace($relative)) { return $false }

    $parts = $relative -split '[\\/]'
    foreach ($part in $parts) {
        if ($ExcludedDirectoryNames -contains $part) { return $true }
    }
    return $false
}

function ConvertTo-SafePlaylistName {
    param([string]$RelativeFolder)

    # Keep the full folder path visible in the playlist name, but flatten it.
    # Example: JPOP\Artist\Album -> JPOP - Artist - Album
    $name = ($RelativeFolder -replace '[\\/]+', ' - ').Trim()

    foreach ($char in [System.IO.Path]::GetInvalidFileNameChars()) {
        $name = $name.Replace([string]$char, '_')
    }

    # Avoid excessively long filenames on Windows/FAT/exFAT.
    if ($name.Length -gt 160) {
        $sha1 = [System.Security.Cryptography.SHA1]::Create()
        try {
            $hashBytes = $sha1.ComputeHash([System.Text.Encoding]::UTF8.GetBytes($RelativeFolder))
            $hash = ([System.BitConverter]::ToString($hashBytes)).Replace('-', '').Substring(0, 8)
        }
        finally {
            $sha1.Dispose()
        }
        $name = $name.Substring(0, 145).TrimEnd() + ' - ' + $hash
    }

    if ([string]::IsNullOrWhiteSpace($name)) {
        $name = 'ROOT'
    }

    return $name
}

function Write-M3U {
    param(
        [string]$PlaylistPath,
        [System.IO.FileInfo[]]$Files
    )

    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add('#EXTM3U')

    foreach ($file in $Files) {
        # Because playlists are written to the USB root, each entry can be a
        # simple path relative to the USB root. Backslashes work naturally on
        # Windows-generated removable media and avoid drive-letter dependence.
        $relative = Get-UsbRelativePath $file.FullName
        $lines.Add($relative)
    }

    # UTF-8 without BOM. This preserves Japanese and other non-ASCII names.
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllLines($PlaylistPath, $lines, $utf8NoBom)
}

Write-Host ''
Write-Host 'MBUX USB Folder Playlist Generator'
Write-Host ('USB root : {0}' -f $Root)
Write-Host ('Mode     : {0}' -f $Mode)
Write-Host ''

# Remove only playlists previously generated by this tool.
$oldGenerated = Get-ChildItem -LiteralPath $Root -File -ErrorAction SilentlyContinue |
    Where-Object {
        $_.Name.StartsWith($PlaylistPrefix, [System.StringComparison]::OrdinalIgnoreCase) -and
        ($_.Extension -ieq '.m3u' -or $_.Extension -ieq '.m3u8')
    }

foreach ($old in $oldGenerated) {
    Remove-Item -LiteralPath $old.FullName -Force
}

$directories = Get-ChildItem -LiteralPath $Root -Directory -Recurse -Force |
    Where-Object { -not (Test-IsExcludedPath $_.FullName) } |
    Sort-Object FullName

$created = 0
$totalEntries = 0

foreach ($dir in $directories) {
    if ($Mode -eq 'Recursive') {
        $files = Get-ChildItem -LiteralPath $dir.FullName -File -Recurse -Force -ErrorAction SilentlyContinue |
            Where-Object {
                -not (Test-IsExcludedPath $_.FullName) -and (Test-IsAudioFile $_)
            } |
            Sort-Object FullName
    }
    else {
        $files = Get-ChildItem -LiteralPath $dir.FullName -File -Force -ErrorAction SilentlyContinue |
            Where-Object { Test-IsAudioFile $_ } |
            Sort-Object Name
    }

    $files = @($files)
    if ($files.Count -eq 0) { continue }

    $relativeFolder = Get-UsbRelativePath $dir.FullName
    $safeName = ConvertTo-SafePlaylistName $relativeFolder
    $playlistName = $PlaylistPrefix + $safeName + $PlaylistExtension
    $playlistPath = Join-Path $Root $playlistName

    Write-M3U -PlaylistPath $playlistPath -Files $files
    $created++
    $totalEntries += $files.Count
    Write-Host ('Created: {0}  ({1} tracks)' -f $playlistName, $files.Count)
}

if ($CreateAllUsbPlaylist) {
    $allFiles = Get-ChildItem -LiteralPath $Root -File -Recurse -Force -ErrorAction SilentlyContinue |
        Where-Object {
            -not (Test-IsExcludedPath $_.FullName) -and (Test-IsAudioFile $_)
        } |
        Sort-Object FullName

    $allFiles = @($allFiles)
    if ($allFiles.Count -gt 0) {
        $allPlaylistPath = Join-Path $Root ($PlaylistPrefix + 'ALL USB' + $PlaylistExtension)
        Write-M3U -PlaylistPath $allPlaylistPath -Files $allFiles
        Write-Host ('Created: {0}  ({1} tracks)' -f (Split-Path -Leaf $allPlaylistPath), $allFiles.Count)
    }
}

Write-Host ''
Write-Host ('Finished: {0} folder playlists created, {1} folder-playlist entries.' -f $created, $totalEntries)
Write-Host 'Existing personal playlists were not touched.'
Write-Host ''
Write-Host 'In MBUX: Media -> USB -> Categories/Playlists -> choose an MBUX playlist.'
Write-Host 'Then enable Random playback or Repeat as desired.'
exit 0
